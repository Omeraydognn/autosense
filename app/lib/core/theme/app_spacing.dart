import 'package:flutter/widgets.dart';

/// 4-pt spacing scale and radii used across the app.
abstract final class Space {
  static const xs = 4.0;
  static const sm = 8.0;
  static const md = 12.0;
  static const lg = 16.0;
  static const xl = 24.0;
  static const xxl = 32.0;

  /// Horizontal page gutter.
  static const page = EdgeInsets.symmetric(horizontal: 20);
}

abstract final class Radii {
  static const sm = 10.0;
  static const md = 14.0;
  static const lg = 20.0;
  static const xl = 28.0;

  static final card = BorderRadius.circular(lg);
  static final chip = BorderRadius.circular(sm);
}

/// Vertical / horizontal gap helpers.
class Gap extends StatelessWidget {
  const Gap(this.size, {super.key});
  final double size;

  @override
  Widget build(BuildContext context) => SizedBox(width: size, height: size);
}
